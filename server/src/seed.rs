fn long_field_report(intro: &str, cases: &[&str], target_chars: usize) -> String {
    let mut result = String::from(intro);
    let mut entry = 0;
    while result.chars().count() < target_chars {
        let case = cases[entry % cases.len()];
        let perspective = PERSPECTIVES[(entry / cases.len() + entry) % PERSPECTIVES.len()];
        result.push_str(&format!(
            "\n\nНаблюдение {:02}.\n\n{}\n\n{}\n\nПромежуточный итог: проверять детали на месте, отмечать источники и не превращать предположения в факты.",
            entry + 1,
            case,
            perspective
        ));
        entry += 1;
    }
    result
}

