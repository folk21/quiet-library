pub async fn seed_demo(pool: &SqlitePool) -> Result<(), sqlx::Error> {
    let mut tx = pool.begin().await?;
    let mut new_authors = 0;
    let mut new_posts = 0;

    for author in AUTHORS {
        let email = format!("demo-{}@invalid.local", author.preferred_number);
        let existing: Option<i64> = sqlx::query_scalar("SELECT id FROM users WHERE email = ?")
            .bind(&email)
            .fetch_optional(&mut *tx)
            .await?;
        let author_id = if let Some(id) = existing {
            id
        } else {
            let reserved: Option<i64> = sqlx::query_scalar("SELECT id FROM users WHERE id = ?")
                .bind(author.preferred_number)
                .fetch_optional(&mut *tx)
                .await?;
            let result = if reserved.is_some() {
                sqlx::query("INSERT INTO users (display_name, email, password_hash, bio, is_demo) VALUES (?, ?, ?, ?, 1)")
                    .bind(author.name)
                    .bind(&email)
                    .bind("!disabled-demo-account")
                    .bind(author.bio)
                    .execute(&mut *tx)
                    .await?
            } else {
                sqlx::query("INSERT INTO users (id, display_name, email, password_hash, bio, is_demo) VALUES (?, ?, ?, ?, ?, 1)")
                    .bind(author.preferred_number)
                    .bind(author.name)
                    .bind(&email)
                    .bind("!disabled-demo-account")
                    .bind(author.bio)
                    .execute(&mut *tx)
                    .await?
            };
            new_authors += 1;
            result.last_insert_rowid()
        };

        for (index, (title, source)) in author.posts.into_iter().enumerate() {
            let key = format!("v2:{}:{}", author.preferred_number, index);
            let tracked: Option<i64> =
                sqlx::query_scalar("SELECT post_id FROM demo_seed_posts WHERE seed_key = ?")
                    .bind(&key)
                    .fetch_optional(&mut *tx)
                    .await?;
            if tracked.is_some() {
                continue;
            }

            let previous_post: Option<i64> = sqlx::query_scalar(
                "SELECT id FROM posts WHERE author_id = ? AND title = ? ORDER BY id LIMIT 1",
            )
            .bind(author_id)
            .bind(title)
            .fetch_optional(&mut *tx)
            .await?;
            let post_id = if let Some(id) = previous_post {
                id
            } else {
                let body = post_content(source);
                let result =
                    sqlx::query("INSERT INTO posts (author_id, title, content) VALUES (?, ?, ?)")
                        .bind(author_id)
                        .bind(title)
                        .bind(body)
                        .execute(&mut *tx)
                        .await?;
                new_posts += 1;
                result.last_insert_rowid()
            };
            sqlx::query("INSERT INTO demo_seed_posts (seed_key, post_id) VALUES (?, ?)")
                .bind(key)
                .bind(post_id)
                .execute(&mut *tx)
                .await?;
        }
    }
    tx.commit().await?;
    info!(new_authors, new_posts, "demo content seed completed");
    Ok(())
}
